SELECT 
FIRSTNAME,
REVERSE(FIRSTNAME  )  AS REVERSEFIRSTNAME ,
CHAR_LENGTH(FIRSTNAME)AS CHARLENGTH
FROM COURSEENROLLMENTS;

SELECT
FIRSTNAME ,
LOCATE  ( 'a'  ,  FIRSTNAME ) AS LOCATE_A_NAME 
FROM COURSEENROLLMENTS;

SELECT 
FIRSTNAME,
REPLACE(FIRSTNAME,'a','o') AS FIRSTNAME_O,
UPPER( FIRSTNAME) AS UPPERCASE
FROM COURSEENROLLMENTS;

SELECT
FIRSTNAME,
LPAD( FIRSTNAME, 12, 0) AS FIRSTNAMELPAD_0
FROM COURSEENROLLMENTS;

SELECT 
COURSENAME,
CONCAT((LEFT( COURSENAME,  2)) ,'-',RIGHT(COURSENAME , 2)) AS COURSELABLE
FROM COURSEENROLLMENTS;

SELECT
FEE,
ROUND(FEE ,1),ROUND(FEE ,0) AS FEE_ROUND
FROM COURSEENROLLMENTS;

SELECT 
FEE,
CEIL(FEE) AS UPWARDFEE,
FLOOR(FEE)AS DOWNWORLDFEE
FROM COURSEENROLLMENTS;
 
SELECT 
FEE,
MOD( FEE , 500) AS FEEDIV
FROM COURSEENROLLMENTS;

SELECT
FEE,
ABS(FEE - 10000) AS ABSFEEDIFFRENCE
FROM COURSEENROLLMENTS;

SELECT 
FEE,
ROUND(FEE*1.18,2)AS ROUNDEDFEE
FROM COURSEENROLLMENTS;

SELECT
FEE,
FORMAT(FEE,2)AS FEESPECTOR
FROM COURSEENROLLMENTS;

SELECT
YEAR(EnrollmentDate) AS Enrollment_Year,
MONTHNAME(EnrollmentDate) AS Enrollment_Month,
DAYNAME(EnrollmentDate) AS Enrollment_Day
FROM COURSEENROLLMENTS;

SELECT 
DATE_FORMAT(EnrollmentDate,'%D,%M,%Y') AS DATEFORMATEnrollmentDate,
DATE_FORMAT(CompletionDate,'%M,%D,%Y') AS DATEFORMATCompletionDate
FROM COURSEENROLLMENTS;

SELECT
TIMESTAMPDIFF(DAY,EnrollmentDate , CompletionDate) AS TOTAL_DAY
FROM COURSEENROLLMENTS;

SELECT
DATE_ADD(DATE_ADD(EnrollmentDate, INTERVAL 1 MONTH),
INTERVAL 10 DAY) AS New_Date
FROM COURSEENROLLMENTS;

SELECT
DATE_ADD(CompletionDate,  Interval -7 DAY) AS NEGATIVENEW_DAYS
FROM COURSEENROLLMENTS;

SELECT
TIMESTAMPDIFF( MONTH,EnrollmentDate ,CompletionDate) AS TOTAL_MONTHS
FROM COURSEENROLLMENTS;


SELECT
DATE_ADD(DATE_ADD(DATE_ADD(Enrollment_Date  , INTERVAL 1 YEAR ), INTERVAL 2 MONTH ), INTERVAL 5 DAY )  AS new_enrollment_date
FROM COURSEENROLLMENTS;

SELECT 
EnrollmentDate,
DAYNAME(  EnrollmentDate ) AS EnrollmentDate_NAME ,
DAYNAME(  CompletionDate ) AS CompletionDate_NAME
FROM COURSEENROLLMENTS;

SELECT 
ENROLLMENTDATE,
TIMESTAMPDIFF( DAY , ENROLLMENTDATE ,CURDATE())AS ENROLMENTDAY
FROM COURSEENROLLMENTS;

SELECT
    DATE_FORMAT(CompletionDate, '%d/%m/%Y') AS OriginalCompletionDate,
    DATE_FORMAT(DATE_ADD(CompletionDate, INTERVAL 15 DAY), '%d/%m/%Y') AS NewCompletionDate
FROM COURSEENROLLMENTS;
